import { readFileSync } from "node:fs";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { lockColumnsSql } from "../src/fix/columns.js";
import { guardFixSql } from "../src/fix/guard.js";
import { lockColumns } from "../src/fix/session.js";
import type { SchemaInfo } from "../src/db/introspect.js";
import { functionFindings, type DatabaseFunction } from "../src/scan/functions.js";
import { scanProject, type ScanResult } from "../src/scan/index.js";
import { ScriptedHuman } from "../src/ui/human.js";
import { copyOf, copyOfExampleApp, EXAMPLE_APP, ROLES_APP } from "./helpers.js";

describe("privilege escalation in the example app", () => {
  let scan: ScanResult;
  beforeAll(async () => {
    scan = await scanProject(EXAMPLE_APP, { code: false });
  });
  afterAll(async () => {
    await scan.project.db.close();
  });

  it("finds that users can set their own profiles.role", () => {
    expect(scan.escalations.map((e) => [`${e.target.label}.${e.column.name}`, e.value.text, e.viaUpdate, e.viaInsert])).toEqual([
      ["profiles.role", "admin", true, false],
    ]);
  });

  it("calls it critical because is_admin() trusts the column", () => {
    const finding = scan.findings.find((f) => f.code === "privilege_escalation")!;
    expect(finding.severity).toBe("critical");
    expect(finding.title).toBe("Users can make themselves admin by setting profiles.role = 'admin' on their own row.");
    expect(finding.detail).toContain("is_admin()");
  });

  it("keeps the ordinary update test away from privilege columns", () => {
    const profiles = scan.results.find((r) => r.target.key === "public.profiles")!;
    expect(profiles.access.owner.update?.allowed).toBe(true);
  });

  it("reads the example's functions and flags only the risky ones", () => {
    const byLabel = Object.fromEntries(scan.findings.filter((f) => f.targetKey.startsWith("function:")).map((f) => [f.label, f.rule]));
    expect(byLabel).toEqual({
      "search_posts()": "db-function-sql-injection",
      "delete_user_notes()": "db-function-bypasses-rls",
    });
  });
});

describe("database checks on the roles fixture", () => {
  let scan: ScanResult;
  beforeAll(async () => {
    scan = await scanProject(ROLES_APP, { code: false });
  });
  afterAll(async () => {
    await scan.project.db.close();
  });

  it("finds a role users can pick when adding their own row", () => {
    expect(scan.escalations.map((e) => [`${e.target.label}.${e.column.name}`, e.value.text, e.viaUpdate, e.viaInsert])).toEqual([
      ["user_roles.role", "admin", false, true],
    ]);
    const finding = scan.findings.find((f) => f.label === "user_roles.role")!;
    expect(finding.severity).toBe("critical");
    expect(finding.detail).toContain("is_moderator()");
  });

  it("counts a trigger, WITH CHECK and column grants as protection", () => {
    expect(scan.escalations.some((e) => e.target.label === "accounts")).toBe(false);
    const accounts = scan.results.find((r) => r.target.key === "public.accounts")!;
    expect(accounts.access.owner.update?.allowed).toBe(true);
  });

  it("flags risky functions, worst problem per function", () => {
    const functions = scan.findings
      .filter((f) => f.targetKey.startsWith("function:"))
      .map((f) => [f.label, f.severity, f.rule]);
    expect(functions).toEqual([
      ["exec_sql()", "critical", "db-function-sql-injection"],
      ["find_members()", "high", "db-function-sql-injection"],
      ["get_email()", "high", "db-function-bypasses-rls"],
      ["touch()", "low", "db-function-search-path"],
    ]);
    const execSql = scan.findings.find((f) => f.label === "exec_sql()")!;
    expect(execSql.title).toContain("can run any SQL they like");
  });

  it("knows which functions are callable and where they live", () => {
    const fn = (name: string) => scan.functions.find((f) => f.name === name)!;
    expect(fn("internal_cleanup").anonCanCall).toBe(false);
    expect(fn("is_moderator").exposed).toBe(false);
    expect(fn("get_email").anonCanCall).toBe(true);
  });

  it("tests tables whose id is generated by default as identity", () => {
    const feedback = scan.results.find((r) => r.target.key === "public.feedback")!;
    expect(feedback.tested).toBe(true);
    expect(feedback.access.anon.insert?.allowed).toBe(true);
  });

  it("suggests a captcha or rate limit when anyone can add rows", () => {
    const finding = scan.findings.find((f) => f.label === "feedback")!;
    expect(finding.title).toBe("Anyone on the internet can add rows in feedback.");
    expect(finding.detail).toContain("rate limit");
  });

  it("flags passwords kept in an app table", () => {
    const finding = scan.findings.find((f) => f.rule === "db-password-column")!;
    expect(finding.label).toBe("members.password");
    expect(finding.severity).toBe("high");
  });
});

describe("locking columns", () => {
  it("writes column grants that the guard accepts", async () => {
    const scan = await scanProject(EXAMPLE_APP, { code: false });
    try {
      const target = scan.escalations[0]!.target;
      const sql = lockColumnsSql(target, scan.escalations);
      expect(sql).toContain('revoke update on table "public"."profiles" from anon, authenticated;');
      expect(sql).toContain('grant update ("id", "full_name", "email", "avatar_url", "created_at") on table "public"."profiles"');
      expect(sql).not.toMatch(/grant update \([^)]*"role"/);
      expect(guardFixSql(sql, target)).toEqual([]);
    } finally {
      await scan.project.db.close();
    }
  });

  it("locks profiles.role, saves it, and a rescan finds nothing", async () => {
    const dir = copyOfExampleApp();
    const scan = await scanProject(dir, { code: false });
    const human = new ScriptedHuman(["yes"]);
    let file: string;
    try {
      const result = await lockColumns(scan, scan.escalations[0]!.target, scan.escalations, human);
      expect(result.status).toBe("saved");
      file = result.file!;
      expect(human.transcript.join("\n")).toContain("✓ Users can't set profiles.role themselves");
      expect(human.transcript.join("\n")).toContain("✓ Users can still edit the rest of their own profiles row");
    } finally {
      await scan.project.db.close();
    }
    expect(file).toMatch(/_vibesecure_fix_profiles_role\.sql$/);
    expect(readFileSync(file, "utf8")).toContain("revoke update");

    const again = await scanProject(dir, { code: false });
    try {
      expect(again.escalations).toEqual([]);
      expect(again.results.find((r) => r.target.key === "public.profiles")!.access.owner.update?.allowed).toBe(true);
    } finally {
      await again.project.db.close();
    }
  });

  it("locks an insert-only hole and says users can't add rows any more", async () => {
    const dir = copyOf(ROLES_APP);
    const scan = await scanProject(dir, { code: false });
    const human = new ScriptedHuman([]);
    try {
      const result = await lockColumns(scan, scan.escalations[0]!.target, scan.escalations, human, { autoSave: true });
      expect(result.status).toBe("saved");
      const shown = human.transcript.join("\n");
      expect(shown).toContain('revoke insert on table "public"."user_roles" from anon, authenticated;');
      expect(shown).toContain('grant insert ("id", "user_id") on table "public"."user_roles"');
      expect(shown).toContain("! Users can no longer add rows to user_roles: role must be filled in");
    } finally {
      await scan.project.db.close();
    }
  });
});

describe("reading function bodies for SQL injection", () => {
  const base: DatabaseFunction = {
    schema: "public",
    exposed: true,
    name: "f",
    args: "id uuid",
    argNames: ["id"],
    returns: "void",
    language: "plpgsql",
    securityDefiner: true,
    searchPathSet: true,
    body: "",
    anonCanCall: true,
    authenticatedCanCall: true,
  };
  const schema: SchemaInfo = { relations: [], storageObjects: null, buckets: [] };
  const rule = (patch: Partial<DatabaseFunction>) =>
    functionFindings([{ ...base, ...patch }], schema).map((f) => `${f.severity} ${f.rule}`);

  it("flags an argument pasted in with ||", () => {
    expect(rule({ body: "begin execute 'delete from posts where id = ''' || id || ''''; end;" })).toEqual([
      "critical db-function-sql-injection",
    ]);
  });

  it("accepts values passed with USING or format('%L')", () => {
    expect(rule({ body: "begin execute 'select * from ' || 'posts' || ' where id = $1' using id; end;" })).toEqual([]);
    expect(rule({ args: "t text", argNames: ["t"], body: "begin execute format('select 1 from posts where title = %L', t); end;" })).toEqual([]);
  });

  it("isn't fooled by an argument's name inside a string", () => {
    expect(rule({ body: "begin execute 'select id from posts'; end;" })).toEqual([]);
  });

  it("rates a security invoker function high, since RLS still applies", () => {
    expect(rule({ securityDefiner: false, args: "q text", argNames: ["q"], body: "begin execute q; end;" })).toEqual([
      "high db-function-sql-injection",
    ]);
  });
});
